"""App icon + TV banner for the Karaoke TV app, generated from one definition of the logo.

The logo: a microphone and three lyric lines, the first one half "sung" like the karaoke wipe on the TV. Colors are
the app's palette (tvapp/.../Theme.kt). Everything is drawn on the 108x108 grid of Android's adaptive icons (the mark
stays inside the 66 px safe zone).

Writes:
  tvapp/art/icon.svg, tvapp/art/banner.svg                    vector sources (the banner's text as outline paths)
  res/drawable/ic_launcher_foreground.xml, ..._background.xml adaptive icon layers (VectorDrawable)
  res/mipmap-anydpi-v26/ic_launcher.xml                       adaptive icon (Android 8+)
  res/mipmap-{m,h,xh,xxh,xxxh}dpi/ic_launcher.png             legacy icon (Android 7)
  res/drawable-xhdpi/banner.png                               320x180 leanback launcher banner

PNGs are rendered from the SVGs with headless Chrome (at 4x / 2x, then downscaled with Pillow).

Run from the repo root:  uv run --with fonttools python tvapp/art/build.py --font <Roboto-Bold.ttf> [--chrome <exe>]
(Roboto Bold, the app's typeface: from a device's /system/fonts or Google Fonts; only needed for the banner text.)
"""
import argparse
import os
import shutil
import subprocess
import tempfile
from pathlib import Path

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from PIL import Image

ART = Path(__file__).resolve().parent
RES = ART.parent / "app" / "src" / "main" / "res"
CHROME_CANDIDATES = [r"C:\Program Files\Google\Chrome\Application\chrome.exe",
                     r"C:\Program Files (x86)\Google\Chrome\Application\chrome.exe",
                     "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome"]
CHROME: Path | None = None   # set in main()


def find_chrome() -> Path:
    names = ("google-chrome", "chromium", "chromium-browser", "chrome")
    for c in [os.environ.get("CHROME"), *(shutil.which(n) for n in names), *CHROME_CANDIDATES]:
        if c and Path(c).is_file():
            return Path(c)
    raise SystemExit("Chrome/Chromium not found: pass --chrome or set CHROME")

# Theme.kt palette
BG = "#121118"
BG_TOP = "#2A1F45"          # a little brighter than the player gradient's top, so the tile reads on the launcher
ACCENT = "#9D6BFF"
SUNG = "#B48CFF"
TEXT = "#F1EFF8"
MUTED = "#9F9BB0"

# the mark: (path data, fill, stroke, stroke width, alpha) on the 108 grid; strokes have round caps
MARK = [
    ("M40 27 a8 8 0 0 1 8 8 v9 a8 8 0 0 1 -16 0 v-9 a8 8 0 0 1 8 -8 z", ACCENT, None, 0, 1.0),     # mic head
    ("M35.5 36 h9 M35.5 41 h9", None, BG, 2, 0.45),                                                 # grille
    ("M28 43 a12 12 0 0 0 24 0", None, SUNG, 3.5, 1.0),                                              # yoke
    ("M40 56 v12", None, SUNG, 3.5, 1.0),                                                            # stem
    ("M33 70 h14", None, SUNG, 3.5, 1.0),                                                            # base
    ("M59.5 31 h15 a2.5 2.5 0 0 1 0 5 h-15 a2.5 2.5 0 0 1 0 -5 z", TEXT, None, 0, 1.0),             # line 1
    ("M59.5 31 h7.5 v5 h-7.5 a2.5 2.5 0 0 1 0 -5 z", SUNG, None, 0, 1.0),                            # line 1, sung part
    ("M59.5 41 h11 a2.5 2.5 0 0 1 0 5 h-11 a2.5 2.5 0 0 1 0 -5 z", TEXT, None, 0, 0.75),            # line 2
    ("M59.5 51 h7 a2.5 2.5 0 0 1 0 5 h-7 a2.5 2.5 0 0 1 0 -5 z", MUTED, None, 0, 0.7),              # line 3
]
MARK_SHIFT = (1.0, 4.6)      # centers the mark (bounding box x 26.3-79.5, y 27-71.8) on (54, 54)
MARK_W, MARK_H = 53.2, 44.8

ICON_SIZES = {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}
ICON_SCALE = 1.4             # the legacy icon has no mask: the mark can be bigger than in the adaptive icon
ICON_RADIUS = 22             # legacy icon corner radius on the 108 grid


def svg_mark() -> str:
    out = []
    for d, fill, stroke, width, alpha in MARK:
        attrs = [f'd="{d}"']
        if fill:
            attrs.append(f'fill="{fill}"')
        else:
            attrs += ['fill="none"', f'stroke="{stroke}"', f'stroke-width="{width}"', 'stroke-linecap="round"']
        if alpha < 1:
            attrs.append(f'opacity="{alpha}"')
        out.append(f"<path {' '.join(attrs)}/>")
    return "\n    ".join(out)


def gradient(gid: str, y1: float, y2: float) -> str:
    return (f'<linearGradient id="{gid}" x1="0" y1="{y1}" x2="0" y2="{y2}" gradientUnits="userSpaceOnUse">'
            f'<stop offset="0" stop-color="{BG_TOP}"/><stop offset="1" stop-color="{BG}"/></linearGradient>')


def icon_svg() -> str:
    dx, dy = MARK_SHIFT
    return f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 108 108" width="108" height="108">
  <!-- Karaoke TV app icon (legacy, Android 7). Generated by build.py; edit the mark there. -->
  <defs>{gradient("bg", 0, 108)}</defs>
  <rect width="108" height="108" rx="{ICON_RADIUS}" fill="url(#bg)"/>
  <g transform="translate(54 54) scale({ICON_SCALE}) translate(-54 -54) translate({dx} {dy})">
    {svg_mark()}
  </g>
</svg>
'''


def text_path(font_file: Path, text: str, size: float, x: float, baseline: float) -> tuple[str, float]:
    """`text` as one SVG path (Roboto glyph outlines, no kerning) starting at x/baseline; returns (d, width)."""
    font = TTFont(font_file)
    glyphs = font.getGlyphSet()
    cmap = font.getBestCmap()
    scale = size / font["head"].unitsPerEm
    pen = SVGPathPen(glyphs)
    cursor = 0.0
    for ch in text:
        name = cmap[ord(ch)]
        glyphs[name].draw(TransformPen(pen, (scale, 0, 0, -scale, x + cursor, baseline)))
        cursor += font["hmtx"][name][0] * scale
    return pen.getCommands(), cursor


def text_metrics(font_file: Path) -> float:
    font = TTFont(font_file)
    return font["OS/2"].sCapHeight / font["head"].unitsPerEm


def banner_svg(font_file: Path) -> str:
    w, h = 320, 180
    mark_scale = 1.8
    size = 46                       # "Karaoke": big enough to read on a launcher tile
    gap = 12
    _, text_w = text_path(font_file, "Karaoke", size, 0, 0)
    mark_w = MARK_W * mark_scale
    left = (w - (mark_w + gap + text_w)) / 2
    cy = h / 2
    # the mark's box center (54, 54 after the shift) goes to (left + mark_w / 2, cy)
    mx, my = left + mark_w / 2, cy
    baseline = cy + text_metrics(font_file) * size / 2
    d, _ = text_path(font_file, "Karaoke", size, left + mark_w + gap, baseline)
    dx, dy = MARK_SHIFT
    return f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w} {h}" width="{w}" height="{h}">
  <!-- Karaoke TV app banner (leanback launcher, 320x180). Generated by build.py; text = Roboto Bold outlines. -->
  <defs>{gradient("bg", 0, h)}</defs>
  <rect width="{w}" height="{h}" fill="url(#bg)"/>
  <g transform="translate({mx:.2f} {my:.2f}) scale({mark_scale}) translate(-54 -54) translate({dx} {dy})">
    {svg_mark()}
  </g>
  <path fill="{TEXT}" d="{d}"/>
</svg>
'''


def vector_foreground() -> str:
    paths = []
    for d, fill, stroke, width, alpha in MARK:
        if fill:
            attrs = f'android:fillColor="{fill}"' + (f' android:fillAlpha="{alpha}"' if alpha < 1 else "")
        else:
            attrs = (f'android:strokeColor="{stroke}" android:strokeWidth="{width}" android:strokeLineCap="round"'
                     + (f' android:strokeAlpha="{alpha}"' if alpha < 1 else ""))
        paths.append(f'        <path android:pathData="{d}" {attrs} />')
    dx, dy = MARK_SHIFT
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Adaptive icon foreground: the logo mark. Generated by tvapp/art/build.py. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">
    <group android:translateX="{dx}" android:translateY="{dy}">
{chr(10).join(paths)}
    </group>
</vector>
'''


def vector_background() -> str:
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Adaptive icon background: the player's dark purple gradient. Generated by tvapp/art/build.py. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android" xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">
    <path android:pathData="M0 0 h108 v108 h-108 z">
        <aapt:attr name="android:fillColor">
            <gradient android:type="linear" android:startX="0" android:startY="0" android:endX="0" android:endY="108">
                <item android:offset="0" android:color="{BG_TOP}" />
                <item android:offset="1" android:color="{BG}" />
            </gradient>
        </aapt:attr>
    </path>
</vector>
'''


ADAPTIVE = '''<?xml version="1.0" encoding="utf-8"?>
<!-- Android 8+: adaptive icon. Generated by tvapp/art/build.py. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@drawable/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
</adaptive-icon>
'''


def render(svg: Path, w: int, h: int, out: Path, oversample: int):
    """Rasterizes `svg` with headless Chrome at `oversample`x, then downscales to w x h (transparent background)."""
    W, H = w * oversample, h * oversample
    with tempfile.TemporaryDirectory() as tmp:
        page = Path(tmp) / "page.html"
        page.write_text(f'<html><body style="margin:0;background:transparent">'
                        f'<img src="{svg.as_uri()}" style="display:block;width:{W}px;height:{H}px"></body></html>',
                        encoding="utf-8")
        shot = Path(tmp) / "shot.png"
        subprocess.run([str(CHROME), "--headless=new", "--disable-gpu", "--hide-scrollbars", "--force-device-scale-factor=1",
                        "--default-background-color=00000000", "--allow-file-access-from-files",
                        f"--window-size={W},{H}", f"--screenshot={shot}", page.as_uri()],
                       check=True, capture_output=True, timeout=60)
        img = Image.open(shot).convert("RGBA").crop((0, 0, W, H))
    out.parent.mkdir(parents=True, exist_ok=True)
    img.resize((w, h), Image.LANCZOS).save(out, optimize=True)
    print(f"{out.relative_to(ART.parent)}  {w}x{h}")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--font", type=Path, required=True, help="Roboto-Bold.ttf (for the banner text)")
    ap.add_argument("--chrome", type=Path, help="Chrome/Chromium executable (default: CHROME, PATH, usual folders)")
    args = ap.parse_args()
    global CHROME
    CHROME = args.chrome or find_chrome()

    def write(path: Path, text: str):
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8", newline="\n")
        print(path.relative_to(ART.parent))

    write(ART / "icon.svg", icon_svg())
    write(ART / "banner.svg", banner_svg(args.font))
    write(RES / "drawable" / "ic_launcher_foreground.xml", vector_foreground())
    write(RES / "drawable" / "ic_launcher_background.xml", vector_background())
    write(RES / "mipmap-anydpi-v26" / "ic_launcher.xml", ADAPTIVE)

    for density, px in ICON_SIZES.items():
        render(ART / "icon.svg", px, px, RES / f"mipmap-{density}" / "ic_launcher.png", 4)
    render(ART / "banner.svg", 320, 180, RES / "drawable-xhdpi" / "banner.png", 2)


if __name__ == "__main__":
    main()
